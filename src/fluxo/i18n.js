const LANG = (() => {
  const saved = localStorage.getItem("lang");
  if (saved && STRINGS[saved]) return saved;
  return (navigator.language || "fr").toLowerCase().startsWith("en") ? "en" : "fr";
})();

export function getLang() {
  return LANG;
}

export function t(key, vars) {
  let s = (STRINGS[LANG] && STRINGS[LANG][key]) ?? STRINGS.fr[key] ?? key;
  if (vars) for (const k in vars) s = s.split(`{${k}}`).join(vars[k]);
  return s;
}

/** Traduit une catégorie d'action renvoyée par le moteur (clé FR canonique). */
export function catLabel(cat) {
  return t(`cat_${cat}`) || cat;
}

/** Traduit un libellé de bloc (nom/description/param) renvoyé par le moteur Rust. */
export function trBlock(s) {
  if (LANG !== "en" || s == null) return s;
  return BLOCK_TR[String(s)] || s;
}

/** Applique les attributs data-i18n* sur le DOM. */
export function applyI18n(root = document) {
  root.querySelectorAll("[data-i18n]").forEach((el) => { el.textContent = t(el.dataset.i18n); });
  root.querySelectorAll("[data-i18n-html]").forEach((el) => { el.innerHTML = t(el.dataset.i18nHtml); });
  root.querySelectorAll("[data-i18n-placeholder]").forEach((el) => { el.placeholder = t(el.dataset.i18nPlaceholder); });
  root.querySelectorAll("[data-i18n-title]").forEach((el) => { el.title = t(el.dataset.i18nTitle); });
}
