/// Description localisée d'une entrée du catalogue (repli sur le français).
export function ollamaModelDescription(model, lang) {
  return lang === "en" ? (model.descriptionEn || model.description) : model.description;
}

/// Vrai si `installed` (liste renvoyée par `ollama_list_models`) contient déjà
/// ce modèle — Ollama suffixe `:latest` aux noms sans tag explicite.
export function ollamaModelInstalled(name, installed) {
  const target = name.includes(":") ? name : `${name}:latest`;
  return (installed || []).some((entry) => entry === name || entry === target);
}
