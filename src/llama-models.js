export function llamaCatalogEntry(filenameOrId) {
  return LLAMA_MODEL_CATALOG.find((model) =>
    model.id === filenameOrId || model.filename === filenameOrId
  ) || null;
}

export function llamaModelLabel(filename) {
  return llamaCatalogEntry(filename)?.label || filename || "Modèle local";
}

/// Description localisée d'une entrée du catalogue (repli sur le français).
export function llamaModelDescription(model, lang) {
  return lang === "en" ? (model.descriptionEn || model.description) : model.description;
}

/// Présentation destinée à quelqu'un qui ne connaît pas ces modèles : qui l'a
/// fait, à quoi il sert, ce qu'on peut en attendre. Écrite d'après la fiche
/// Hugging Face de chaque modèle, pas recopiée : une carte de modèle s'adresse
/// à des praticiens et parle de benchmarks, ce qui n'aide personne à choisir.
export function llamaModelAbout(model, lang) {
  return lang === "en" ? (model.aboutEn || model.about || "") : (model.about || "");
}

/// Page du modèle sur Hugging Face, déduite de l'URL de téléchargement.
///
/// Déduite plutôt que stockée : un champ de plus par entrée finirait par
/// diverger de l'URL réelle, alors que celle-ci est vérifiée à chaque
/// téléchargement.
export function llamaModelCardUrl(model) {
  const match = /^https:\/\/huggingface\.co\/([^/]+\/[^/]+)\/resolve\//.exec(model?.url || "");
  return match ? `https://huggingface.co/${match[1]}` : "";
}
